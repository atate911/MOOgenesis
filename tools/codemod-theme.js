#!/usr/bin/env node
// Theme-v2 screen override generator.
// Many screens inject their own <style> blocks with hard-coded indigo surfaces and brass/gold ornament (v1 look). Instead of
// editing every screen module, this tool scans js/ui/*.js for CSS rules that use those colours and emits re-coloured copies,
// scoped to :root[data-theme="v2"] (higher specificity than the originals), into the GENERATED block of css/theme-v2.css.
//   node tools/codemod-theme.js          (rewrites the block; idempotent; re-run after changing screen styles)
//   node tools/codemod-theme.js --dry    (prints stats only)
// Rules: indigo/violet dark surfaces -> cool gunmetal (same lightness, low chroma); brass (hue 30-60, sat .3-.7) ->
// steel on borders/shadows, ink on text, accent on bright opaque fills; saturated semantic gold/cyan/red are left alone.
'use strict';
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const cssFile = path.join(root, 'css/theme-v2.css');
const BEGIN = '/* >>> GENERATED by tools/codemod-theme.js (do not edit by hand) >>> */';
const END = '/* <<< GENERATED <<< */';

function parseColor(s) {
  s = s.trim();
  let m = /^#([0-9a-f]{3,8})$/i.exec(s);
  if (m) {
    let h = m[1]; if (h.length === 3 || h.length === 4) h = h.split('').map(c => c + c).join('');
    return { r: parseInt(h.slice(0, 2), 16), g: parseInt(h.slice(2, 4), 16), b: parseInt(h.slice(4, 6), 16), a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1 };
  }
  m = /^rgba?\(\s*([\d.]+)[ ,]+([\d.]+)[ ,]+([\d.]+)(?:[ ,/]+([\d.]+%?))?\s*\)$/i.exec(s);
  if (m) { let a = m[4] === undefined ? 1 : (m[4].endsWith('%') ? parseFloat(m[4]) / 100 : parseFloat(m[4])); return { r: +m[1], g: +m[2], b: +m[3], a }; }
  return null;
}
function hsl(c) {
  const r = c.r / 255, g = c.g / 255, b = c.b / 255, mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2, d = mx - mn;
  let h = 0, s = 0;
  if (d) { s = d / (1 - Math.abs(2 * l - 1)); h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h *= 60; if (h < 0) h += 360; }
  return { h, s, l };
}
function fromHsl(h, s, l, a) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs((h / 60) % 2 - 1)), m = l - c / 2;
  let r = 0, g = 0, b = 0;
  if (h < 60) [r, g, b] = [c, x, 0]; else if (h < 120) [r, g, b] = [x, c, 0]; else if (h < 180) [r, g, b] = [0, c, x];
  else if (h < 240) [r, g, b] = [0, x, c]; else if (h < 300) [r, g, b] = [x, 0, c]; else [r, g, b] = [c, 0, x];
  const R = Math.round((r + m) * 255), G = Math.round((g + m) * 255), B = Math.round((b + m) * 255);
  return a >= 0.999 ? '#' + [R, G, B].map(v => v.toString(16).padStart(2, '0')).join('') : 'rgba(' + R + ',' + G + ',' + B + ',' + +a.toFixed(3) + ')';
}
// returns a replacement string or null (leave as is)
function mapColor(src, prop) {
  const c = parseColor(src); if (!c) return null;
  const { h, s, l } = hsl(c);
  const isText = /^(color|fill|stroke|text-shadow|-webkit-text-fill-color)$/.test(prop), isBg = /^background/.test(prop);
  // indigo / violet dark surfaces
  if (h >= 205 && h <= 295 && s > 0.2 && l < 0.45) return fromHsl(212, Math.min(0.2, s * 0.32), l * 0.9, c.a);
  // light lavender text/lines (mist/fog family)
  if (h >= 205 && h <= 275 && s > 0.2 && l >= 0.45 && l < 0.8 && !isBg) return fromHsl(210, 0.1, Math.min(0.72, l * 0.98), c.a);
  // brass family (decorative gold)
  if (h >= 28 && h <= 60 && s >= 0.3 && s <= 0.72 && l >= 0.25) {
    if (isText) return l > 0.72 ? '#e9eef3' : '#8fa3b7';
    if (isBg && c.a >= 0.9 && l > 0.45) return fromHsl(193, Math.min(0.78, s * 1.25), l * 0.92, c.a);   // bright opaque fill = accent
    if (isBg && c.a < 0.9) return fromHsl(205, 0.12, Math.max(0.5, l * 0.9), c.a * 0.9);
    return fromHsl(208, 0.13, Math.max(0.42, l * 0.78), c.a);
  }
  // dark brass (brass-lo and friends)
  if (h >= 28 && h <= 60 && s >= 0.25 && l < 0.25) return fromHsl(210, 0.2, l * 1.3, c.a);
  return null;
}
const COLOR_RE = /#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^()]*\)/g;

function scan(text, file, out) {
  const stack = []; let buf = '';
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === '{') { stack.push({ pre: buf.trim(), body: '', kids: false }); if (stack.length > 1) stack[stack.length - 2].kids = true; buf = ''; }
    else if (ch === '}') {
      const top = stack.pop(); if (!top) { buf = ''; continue; }
      const body = (buf.trim() ? buf : top.body); buf = '';
      if (!top.kids) emit(top.pre, body, stack, out, file);
    } else if (ch === ';') { if (stack.length) { buf += ch; } else buf = ''; }
    else buf += ch;
  }
}
function emit(selector, body, stack, out, file) {
  selector = selector.replace(/\/\*[\s\S]*?\*\//g, '').split(/[`;]/).pop().trim();
  if (!selector || /[`$=]|\bfunction\b|\breturn\b/.test(selector) || selector.length > 400) return;
  if (!/^[.#:\w\[\]\s,>~+*\-"'()=%]+$/.test(selector.replace(/\n/g, ' ')) || selector.startsWith('@') || /^(from|to|\d+%)/.test(selector)) return;
  if (/\(/.test(selector.replace(/:(not|is|where|has|nth-child|nth-of-type|nth-last-child)\([^()]*\)/g, ''))) return;   // JS call sites, not selectors
  if (body.includes('${') || body.includes('`')) return;
  if (stack.some(s => /@keyframes/.test(s.pre))) return;
  const decls = body.split(';').map(d => d.trim()).filter(Boolean);
  const keep = [];
  for (const d of decls) {
    const m = /^([-a-z]+)\s*:\s*([\s\S]+)$/.exec(d); if (!m) return;      // not a pure declaration list -> JS, skip
    const prop = m[1];
    if (!/^(background|border|box-shadow|color|fill|stroke|text-shadow|outline|filter|--|-webkit-text-fill-color|caret-color|accent-color)/.test(prop) && !/^[-a-z]+$/.test(prop)) return;
    if (/Math\.|\?|\bw \*|\bhh\b/.test(m[2])) return;
    const val = m[2].replace(/!important/g, '').trim();
    if (prop.startsWith('--') && !/color|c\d|^--(e1|e2)/.test(prop)) { /* custom props may carry colours too */ }
    let changed = false;
    const P = prop.startsWith('--') ? 'border-color' : prop;
    const warm = c => { const k = parseColor(c); if (!k) return false; const q = hsl(k); return q.h >= 28 && q.h <= 60 && q.s > 0.3; };
    const all = val.match(COLOR_RE) || [];
    const keepWarm = all.some(c => warm(c) && !mapColor(c, P));     // semantic gold in the same value (e.g. a gold gradient): leave the whole warm family alone
    const nv = val.replace(COLOR_RE, c => { if (keepWarm && warm(c)) return c; const r = mapColor(c, P); if (r) { changed = true; return r; } return c; });
    if (changed) keep.push(prop + ':' + nv);
  }
  if (!keep.length) return;
  const media = stack.map(s => s.pre).filter(p => /^@(media|supports)/.test(p));
  const sel = selector.split(',').map(s => ':root[data-theme="v2"] ' + s.trim()).join(', ');
  out.push({ file, media: media.join(' '), css: sel + ' { ' + keep.join('; ') + '; }' });
}

const dir = path.join(root, 'js/ui');
const out = [];
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js') && f !== 'styleguide.js').sort()) scan(fs.readFileSync(path.join(dir, f), 'utf8'), f, out);
// de-dupe identical rules, group by file
const seen = new Set(), lines = [];
let curFile = '';
for (const r of out) {
  const line = r.media ? r.media + ' { ' + r.css + ' }' : r.css;
  if (seen.has(line)) continue; seen.add(line);
  if (r.file !== curFile) { curFile = r.file; lines.push('/* ' + r.file + ' */'); }
  lines.push(line);
}
console.log('rules generated: ' + seen.size + ' from ' + new Set(out.map(r => r.file)).size + ' files');
if (process.argv.includes('--dry')) process.exit(0);
let css = fs.readFileSync(cssFile, 'utf8');
const a = css.indexOf(BEGIN), b = css.indexOf(END);
const block = BEGIN + '\n' + lines.join('\n') + '\n' + END;
if (a >= 0 && b > a) css = css.slice(0, a) + block + css.slice(b + END.length);
else css = css.trimEnd() + '\n\n/* ---- 15. screen overrides (generated from the screens\' own <style> blocks) ------------------------------------ */\n' + block + '\n';
fs.writeFileSync(cssFile, css);
